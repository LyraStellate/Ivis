package tools

import "os/exec"

// tracker は起動した木をまとめて掴むための取っ手 (#470913)。
//
// 見張りが知りたいのは「木全体が仕事をしているか」であって、シェル 1 つの
// 様子ではない。シェルは子を待っているだけなので、いつ見ても動いていない
// ように見える。
//
// 実装は OS ごとに分かれる。Windows はジョブオブジェクト、POSIX はプロセス
// グループで木を掴む。
type tracker interface {
	// adopt は起動した直後に呼ぶ。ここで木を掴む。
	adopt(cmd *exec.Cmd)
	// work は「これまでに行われた仕事」の目盛り。増えていれば動いている。
	//
	// 測れない環境では ok=false を返す。そのときは見張りが出力だけで判じる
	// 形に落ちる — 測れないことを黙って「動いている」ことにはしない。
	work() (uint64, bool)
	// kill は木ごと止める。
	kill()
	// close は掴んだものを離す。プロセスは止めない。
	close()
}
